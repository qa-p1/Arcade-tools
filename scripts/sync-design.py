#!/usr/bin/env python3
"""Copy the Arcade design kit from an Arcade Link checkout at the pinned tag.

    python3 scripts/sync-design.py --link ../Arcade-Link   # an existing checkout
    python3 scripts/sync-design.py                         # clones the tag

The tag is the one Cargo.toml pins arcade-link to. The checkout's HEAD must be
that tag's commit. The files land in src-ui/design/ (stylesheet, icons,
format helpers, Inter, the app glyphs) and src-tauri/icons/ (Tools' launcher
icon set), and their hashes go into the "Arcade design kit" section of
VENDORED, which scripts/verify-vendored.py checks.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LINK_URL = "https://github.com/qa-p1/Arcade-Link"
HEADER = "Arcade design kit"
# (source in Link, destination here); a trailing slash copies the folder's files.
FILES = [
    ("design/css/arcade.css", "src-ui/design/arcade.css"),
    ("design/css/icons.ts", "src-ui/design/icons.ts"),
    ("design/css/format.ts", "src-ui/design/format.ts"),
    ("design/fonts/InterVariable.woff2", "src-ui/design/fonts/InterVariable.woff2"),
    ("design/fonts/OFL.txt", "src-ui/design/fonts/OFL.txt"),
    ("design/glyphs/", "src-ui/design/glyphs/"),
    ("design/app-icons/tools/tauri/", "src-tauri/icons/"),
    ("design/app-icons/tools/icon.svg", "assets/icon.svg"),
]


def pinned_tag() -> str:
    match = re.search(r'arcade-link = \{[^}]*tag = "([^"]+)"', (ROOT / "Cargo.toml").read_text())
    if not match:
        raise SystemExit("Cargo.toml doesn't pin arcade-link to a tag")
    return match.group(1)


def git(link: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(link), *args], check=True, capture_output=True, text=True).stdout.strip()


def pairs(link: Path) -> list[tuple[Path, str, str]]:
    out = []
    for source, target in FILES:
        if source.endswith("/"):
            files = sorted(p for p in (link / source).iterdir() if p.is_file())
            if not files:
                raise SystemExit(f"{source} is empty in the Link checkout")
            out += [(p, f"{source}{p.name}", f"{target}{p.name}") for p in files]
        else:
            out.append((link / source, source, target))
    return out


def sync(link: Path, tag: str) -> None:
    commit = git(link, "rev-parse", "HEAD")
    tagged = git(link, "rev-parse", f"{tag}^{{commit}}")
    if commit != tagged:
        raise SystemExit(f"{link} is at {commit[:12]}, not {tag} ({tagged[:12]})")
    for folder in ("src-ui/design/glyphs",):
        shutil.rmtree(ROOT / folder, ignore_errors=True)
    lines = []
    for path, source, target in pairs(link):
        destination = ROOT / target
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, destination)
        digest = hashlib.sha256(destination.read_bytes()).hexdigest()
        lines.append(f"{target}  sha256:{digest}  source:{source}")
    section = "\n".join([
        HEADER,
        f"Source: {LINK_URL}",
        f"Tag: {tag}",
        f"Commit: {commit}",
        "License: MIT OR Apache-2.0; Inter is under the SIL Open Font License 1.1",
        "(src-ui/design/fonts/OFL.txt). Generated by Link's design/generate.py and",
        "copied unchanged by scripts/sync-design.py; never edit these files here.",
        "",
        *lines,
    ])
    vendored = ROOT / "VENDORED"
    text = vendored.read_text()
    blocks = text.rstrip("\n").split("\n\n")
    start = next((i for i, block in enumerate(blocks) if block.startswith(HEADER + "\n")), None)
    if start is None:
        text = text.rstrip("\n") + "\n\n" + section + "\n"
    else:
        # The section is its header paragraph plus the hash paragraph after it.
        blocks[start:start + 2] = [section]
        text = "\n\n".join(blocks) + "\n"
    vendored.write_text(text)
    print(f"Synced {len(lines)} design kit files from Link {tag} ({commit[:12]})")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--link", type=Path, help="an Arcade Link checkout at the pinned tag")
    args = parser.parse_args(argv)
    tag = pinned_tag()
    if args.link:
        sync(args.link.resolve(), tag)
        return 0
    with tempfile.TemporaryDirectory() as temp:
        checkout = Path(temp) / "Arcade-Link"
        subprocess.run(["git", "clone", "--quiet", "--depth", "1", "--branch", tag, LINK_URL, str(checkout)], check=True)
        sync(checkout, tag)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
